"""Parametric RAG (Su et al. 2025): per-passage document augmentation and LoRA encoding.

Follows the official implementation (github.com/oneal2000/PRAG, src/augment.py,
src/encode.py, src/prompt_template.py): one rewrite and three QA pairs per
passage generated by the downstream LLM, then one LoRA per passage on the FFN
matrices with r=2, alpha=32, no dropout, lr 3e-4, 1 epoch, batch size 1, and
the loss taken over the full prompt+answer sequence.

Usage:
    python -m doc_knowledge.prag augment --passages passages.jsonl --out augment.jsonl --vllm-url http://localhost:8000
    python -m doc_knowledge.prag train --augment augment.jsonl --out-dir /root/adapters/prag --seeds 0 1 2
"""

import argparse
import json
import re
import time
from pathlib import Path

import httpx

from .prompts import ANSWER_TEMPLATE, build_user_prompt
from .retriever import load_jsonl

REWRITE_PROMPT = (
    "Rewrite the following passage. While keeping the entities, proper nouns, and key details such as names, "
    "locations, and terminology intact, create a new version of the text that expresses the same ideas in a "
    "different way. Make sure the revised passage is distinct from the original one, but preserves the core "
    "meaning and relevant information.\n{passage}"
)
QA_PROMPT = (
    "I will provide a passage of text, and you need to generate three different questions based on the content "
    "of this passage. Each question should be answerable using the information provided in the passage. "
    "Additionally, please provide an appropriate answer for each question derived from the passage.\n"
    "You need to generate the question and answer in the following format:\n"
    "[\n"
    "    {{\n"
    '        "question": "What is the capital of France?",\n'
    '        "answer": "Paris"\n'
    '        "full_answer": "The capital of France is Paris."\n'
    "    }}, \n"
    "]\n"
    "This list should have at least three elements. You only need to output this list in the above format.\n"
    "Passage:\n{passage}"
)
TARGET_MODULES = ["down_proj", "gate_proj", "up_proj"]


def parse_qa_list(text: str) -> list[dict]:
    """Extract question/answer pairs from the generator's loosely formatted JSON.

    Args:
        text: Raw LLM output that should contain a JSON list.

    Returns:
        Dicts with "question" and "answer"; empty if nothing parseable was found.
    """
    start, end = text.find("["), text.rfind("]")
    if start != -1 and end > start:
        try:
            items = json.loads(text[start : end + 1])
            return [
                {"question": str(i["question"]), "answer": str(i["answer"])}
                for i in items
                if isinstance(i, dict) and "question" in i and "answer" in i
            ]
        except json.JSONDecodeError:
            pass
    pattern = r'"question"\s*:\s*"((?:[^"\\]|\\.)*)"\s*,?\s*"answer"\s*:\s*"((?:[^"\\]|\\.)*)"'
    return [{"question": q, "answer": a} for q, a in re.findall(pattern, text)]


def _chat(client: httpx.Client, vllm_url: str, model: str, prompt: str, max_tokens: int) -> str:
    resp = client.post(
        f"{vllm_url}/v1/chat/completions",
        json={
            "model": model,
            "messages": [{"role": "user", "content": prompt}],
            "temperature": 0.0,
            "max_tokens": max_tokens,
        },
    )
    resp.raise_for_status()
    return resp.json()["choices"][0]["message"]["content"]


def augment(passages: list[dict], vllm_url: str, model: str, out_path: str | Path) -> list[dict]:
    """Generate one rewrite and three QA pairs per passage with the downstream LLM.

    Args:
        passages: Passage dicts with "id" and "text".
        vllm_url: Base URL of the vLLM server.
        model: Served model name.
        out_path: JSON-lines output path.

    Returns:
        Augmentation records with passage_id, passage, rewrite, qa, seconds.
    """
    records = []
    with httpx.Client(timeout=300.0) as client, open(out_path, "w") as f:
        for p in passages:
            t0 = time.perf_counter()
            rewrite = _chat(client, vllm_url, model, REWRITE_PROMPT.format(passage=p["text"]), 1024).strip()
            qa = []
            for _ in range(3):
                qa = parse_qa_list(_chat(client, vllm_url, model, QA_PROMPT.format(passage=p["text"]), 1024))
                if qa:
                    break
            rec = {
                "passage_id": p["id"],
                "passage": p["text"],
                "rewrite": rewrite,
                "qa": qa[:3],
                "seconds": time.perf_counter() - t0,
            }
            f.write(json.dumps(rec) + "\n")
            f.flush()
            records.append(rec)
    return records


def training_sequences(tokenizer, record: dict, chat_template: str | None = None) -> list[list[int]]:
    """Token sequences for one passage, mirroring PRAG encode.get_train_data.

    The first ceil(n/2) QA pairs are paired with both the original passage and
    its rewrite; the remaining pairs are trained without a passage.

    Args:
        tokenizer: Base-model tokenizer.
        record: Augmentation record.
        chat_template: Optional chat template overriding the tokenizer default.

    Returns:
        Token id lists (prompt + "The answer is ...").
    """
    qas = record["qa"]
    with_passage = (len(qas) + 1) // 2
    sequences = []
    for i, qa in enumerate(qas):
        contexts = [[record["passage"]], [record["rewrite"]]] if i < with_passage else [None]
        for passages in contexts:
            prompt_ids = tokenizer.apply_chat_template(
                [{"role": "user", "content": build_user_prompt(qa["question"], passages)}],
                chat_template=chat_template,
                add_generation_prompt=True,
                tokenize=True,
            )
            answer = qa["answer"].strip()
            answer = answer if answer.endswith(".") else answer + "."
            sequences.append(prompt_ids + tokenizer.encode(ANSWER_TEMPLATE.format(answer=answer), add_special_tokens=False))
    return sequences


def train(
    records: list[dict],
    model_name: str,
    out_dir: str | Path,
    seeds: list[int],
    chat_template: str | None = None,
    rank: int = 2,
    alpha: int = 32,
    lr: float = 3e-4,
    epochs: int = 1,
) -> dict:
    """Train one LoRA per passage and seed.

    Args:
        records: Augmentation records.
        model_name: Base model to load.
        out_dir: Root output directory; adapters go to <out_dir>/seed<s>/<passage_id>.
        seeds: Seeds controlling LoRA initialisation.
        chat_template: Optional chat template string.
        rank: LoRA rank.
        alpha: LoRA alpha.
        lr: AdamW learning rate.
        epochs: Training epochs.

    Returns:
        Per-seed, per-passage training seconds.
    """
    import torch
    from peft import LoraConfig, get_peft_model
    from transformers import AutoModelForCausalLM, AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(model_name)
    base = AutoModelForCausalLM.from_pretrained(model_name, torch_dtype=torch.bfloat16, device_map="cuda")
    config = LoraConfig(task_type="CAUSAL_LM", target_modules=TARGET_MODULES, r=rank, lora_alpha=alpha, lora_dropout=0.0)
    log = {}
    model = None
    for seed in seeds:
        torch.manual_seed(seed)
        if model is None:
            model = get_peft_model(base, config)
        else:
            for module in model.modules():
                if hasattr(module, "reset_lora_parameters"):
                    module.reset_lora_parameters("default", True)
        init = {k: v.detach().clone() for k, v in model.state_dict().items() if "lora_" in k}
        log[seed] = {}
        for rec in records:
            target = Path(out_dir) / f"seed{seed}" / rec["passage_id"].replace("#", "_")
            if (target / "adapter_model.safetensors").exists():
                continue
            model.load_state_dict(init, strict=False)
            optimizer = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad], lr=lr)
            seqs = training_sequences(tokenizer, rec, chat_template)
            t0 = time.perf_counter()
            model.train()
            for _ in range(epochs):
                for ids in seqs:
                    input_ids = torch.tensor([ids], device=model.device)
                    loss = model(input_ids=input_ids, labels=input_ids).loss
                    optimizer.zero_grad()
                    loss.backward()
                    optimizer.step()
            torch.cuda.synchronize()
            log[seed][rec["passage_id"]] = time.perf_counter() - t0
            model.save_pretrained(target)
    return log


def adapter_dir(root: str | Path, seed: int, passage_id: str) -> Path:
    """Location of a trained PRAG adapter.

    Args:
        root: Root passed to train().
        seed: Training seed.
        passage_id: Passage id.

    Returns:
        Adapter directory path.
    """
    return Path(root) / f"seed{seed}" / passage_id.replace("#", "_")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    aug = sub.add_parser("augment")
    aug.add_argument("--passages", required=True)
    aug.add_argument("--out", required=True)
    aug.add_argument("--vllm-url", default="http://localhost:8000")
    aug.add_argument("--model", default="Qwen/Qwen3-4B-Instruct-2507")
    tr = sub.add_parser("train")
    tr.add_argument("--augment", required=True)
    tr.add_argument("--out-dir", required=True)
    tr.add_argument("--model", default="Qwen/Qwen3-4B-Instruct-2507")
    tr.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    tr.add_argument("--chat-template", default=None, help="Path to a jinja chat template")
    tr.add_argument("--epochs", type=int, default=1)
    args = parser.parse_args()

    if args.cmd == "augment":
        augment(load_jsonl(args.passages), args.vllm_url.rstrip("/"), args.model, args.out)
    else:
        template = Path(args.chat_template).read_text() if args.chat_template else None
        log = train(load_jsonl(args.augment), args.model, args.out_dir, args.seeds, template, epochs=args.epochs)
        Path(args.out_dir).mkdir(parents=True, exist_ok=True)
        (Path(args.out_dir) / "train_log.json").write_text(json.dumps(log, indent=2))


if __name__ == "__main__":
    main()
